#!/usr/bin/env python3
"""Assemble the Drive inventory from the folder walk, the probes and the triage.

  python3 pipeline/scans/inventory/build.py [tree.json probes.jsonl]

The inputs default to data/tree.json and data/probes.jsonl. tree.json is the walk of the Drive folders ({"nodes": {id: {id, parentId, kind
F|P|O, size, title}}}), probes.jsonl one probe.py result per line with its
"drive_id" (the latest line for an id wins). Writes inventory.json and INVENTORY.md beside this file, joining
manifest.yaml's triage by Drive id.
"""

import json
import os
import re
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from classify import is_unicode_font  # noqa: E402

# First match wins, so the more specific kinds come first.
KIND_PATTERNS = [
    ("lithograph", r"lithograph|stone print|photozincograph"),
    ("commentary", r"teeka|tika|steek|darpan|arth|santhe?y?a|parbodh|translation|vyakhya|viakaran"),
    ("compilation", r"gutka|nitnem|pothi\b(?!.*\bms\b)|mahatam|ਗੁਟਕਾ|ਨਿਤਨੇਮ|ਪੋਥੀ|bani sheet"),
    ("manuscript", r"\bms\b|\bmss\b|manuscript|handwritten|hand-written|saroop|\bbir\b|folios|\bff\.|pothi"),
]


def folder_path(tree: dict, node_id: str) -> str:
    parts = []
    node = tree.get(tree[node_id]["parentId"])
    while node:
        parts.append(node["title"])
        node = tree.get(node["parentId"])
    return " / ".join(reversed(parts))


def guess_kind(title: str, path: str) -> str:
    """manuscript | lithograph | commentary | compilation | print, from the title
    (and folder) alone: a first sort for reading the list, not a ruling."""
    text = f"{title} {path}".lower()
    for kind, pattern in KIND_PATTERNS:
        if re.search(pattern, text):
            return kind
    return "print"


def build_rows(tree: dict, probes: dict, manifest: dict) -> list[dict]:
    rows = []
    for node in tree.values():
        if node["kind"] != "P":
            continue
        path = folder_path(tree, node["id"])
        probe = probes.get(node["id"], {})
        row = {
            "drive_id": node["id"],
            "title": node["title"],
            "folder": path,
            "size_mb": round(node.get("size", 0) / 1e6, 1),
            "pages": probe.get("pages"),
            "kind": guess_kind(node["title"], path),
            "text_layer": probe.get("text_layer", "unprobed"),
            "encodings": probe.get("encodings", []),
            # re-filtered so fonts added to the Latin list since the probe drop out
            "unknown_fonts": [f for f in probe.get("unknown_fonts", []) if not is_unicode_font(f)],
            "scripts": {k: round(v, 2) for k, v in probe.get("scripts", {}).items() if v >= 0.05},
            "unmapped_glyphs": probe.get("unmapped_glyphs", False),
            "probe": probe.get("probe"),
        }
        if node["id"] in manifest:
            row["triage"] = manifest[node["id"]]
        rows.append(row)
    rows.sort(key=lambda r: (r["folder"], r["title"].lower()))
    return rows


def image_counts(tree: dict) -> dict[str, int]:
    counts = Counter(n["parentId"] for n in tree.values() if n["kind"] == "O")
    return {folder_path(tree, next(n["id"] for n in tree.values() if n["parentId"] == p)): c
            for p, c in counts.items()}


def load_manifest() -> dict:
    import yaml
    m = yaml.safe_load(open(os.path.join(HERE, "..", "manifest.yaml")))
    return {f["drive_id"]: {"decision": f.get("decision"), "tier": f.get("tier"), "text_layer": f.get("text_layer")}
            for f in m["files"] if f.get("drive_id")}


LAYER_ORDER = ["unicode", "mixed", "legacy", "garbled", "latin", "none", "unindexed", "unprobed"]


def render_markdown(rows: list[dict], images: dict[str, int]) -> str:
    by_layer = Counter(r["text_layer"] for r in rows)
    out = [
        "# Drive inventory",
        "",
        "Every PDF in the Gurbani folders of the Drive, with what its text layer holds.",
        "Generated by `build.py`; do not edit by hand. Curated triage stays in `../manifest.yaml`.",
        "",
        "Text layer: **unicode** Unicode Gurmukhi (or Devanagari/Perso-Arabic) · **mixed** Unicode and a",
        "legacy font · **legacy** a legacy Gurmukhi font (encoding named) · **garbled** bad OCR · **latin**",
        "English or romanised only · **none** page images only · **unindexed** too large for Drive's",
        "text extraction and the download limit: probe a synced copy with `probe_local.py` ·",
        "**unprobed** not checked yet.",
        "Kind is guessed from the title, as a first sort.",
        "",
        "| text layer | files |",
        "|---|---|",
        *[f"| {k} | {by_layer[k]} |" for k in LAYER_ORDER if by_layer[k]],
        "",
    ]
    folder = None
    for r in rows:
        if r["folder"] != folder:
            folder = r["folder"]
            out += ["", f"## {folder}", "", "| title | kind | pages | MB | text layer | scripts | triage |", "|---|---|---|---|---|---|---|"]
        layer = r["text_layer"]
        if r["encodings"]:
            layer += f" ({', '.join(r['encodings'])})"
        if r["unmapped_glyphs"]:
            layer += " (glyph ids only: needs OCR)"
        if r["unknown_fonts"]:
            layer += f"; unknown fonts: {', '.join(r['unknown_fonts'][:3])}"
        scripts = ", ".join(f"{k} {int(v * 100)}%" for k, v in r["scripts"].items())
        triage = r.get("triage", {}).get("decision") or ""
        title = r["title"].replace("|", "/")
        out.append(f"| [{title}](https://drive.google.com/file/d/{r['drive_id']}) | {r['kind']} | {r['pages'] or ''} | {r['size_mb']} | {layer} | {scripts} | {triage} |")
    if images:
        out += ["", "## Folders of page images", "", "| folder | images |", "|---|---|"]
        out += [f"| {f} | {n} |" for f, n in sorted(images.items())]
    return "\n".join(out) + "\n"


def main(tree_path: str, probes_path: str) -> None:
    tree = json.load(open(tree_path))["nodes"]
    probes = {}
    if os.path.exists(probes_path):
        for line in open(probes_path):
            if line.strip():
                p = json.loads(line)
                probes[p["drive_id"]] = p
    rows = build_rows(tree, probes, load_manifest())
    images = image_counts(tree)
    json.dump({"files": rows, "image_folders": images}, open(os.path.join(HERE, "inventory.json"), "w"),
              ensure_ascii=False, indent=1)
    open(os.path.join(HERE, "INVENTORY.md"), "w").write(render_markdown(rows, images))
    print(f"{len(rows)} PDFs, {sum(images.values())} images in {len(images)} folders")


if __name__ == "__main__":
    data = os.path.join(HERE, "data")
    args = sys.argv[1:] or [os.path.join(data, "tree.json"), os.path.join(data, "probes.jsonl")]
    main(*args)
